def extract_text_from_pdf(pdf_path: Path) -> str:
    text_list = []

    # 1. Attempt standard digital text extraction first
    try:
        with open(pdf_path, "rb") as f:
            reader = pypdf.PdfReader(f)
            for page in reader.pages:
                text_list.append(page.extract_text() or "")
    except Exception as parse_err:
        print(f"⚠️ Normal PDF parsing failed for {pdf_path.name}: {parse_err}")

    extracted_text = "\n".join(text_list).strip()

    # 2. If no text was extracted, fall back to OCR
    if not extracted_text:
        print(f"🔍 Document '{pdf_path.name}' is scanned. Activating OCR fallback (Hebrew + English)... ")
        try:
            # Convert PDF pages to PIL image objects
            images = convert_from_path(str(pdf_path), dpi=200)
            ocr_pages = []

            for idx, img in enumerate(images):
                # Run Tesseract with both Hebrew (heb) and English (eng) languages
                page_text = pytesseract.image_to_string(img, lang="heb+eng")
                ocr_pages.append(page_text)

            extracted_text = "\n".join(ocr_pages).strip()
            print(f"✨ OCR completed: Extracted {len(extracted_text)} characters from {len(images)} pages.")
        except Exception as ocr_err:
            print(f"❌ OCR processing failed for {pdf_path.name}: {ocr_err}")

    return extracted_text

