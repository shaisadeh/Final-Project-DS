def retrieve_and_rerank(query: str, top_k_bi: int = 20, top_k_cross: int = 3) -> List[Dict[str, Any]]:
    # 1. Conditionally translate query only if Hebrew characters are detected
    is_hebrew = contains_hebrew(query)
    translated_query = translate_query_to_english(query) if is_hebrew else query

    print(f"🔍 Input Search Query: {query}")
    if is_hebrew:
        print(f"🇬🇧 Translated Query: {translated_query}\n")

    # 2. Retrieve top matches using English vectors
    query_embedding = embedding_model.encode([translated_query], normalize_embeddings=True).tolist()

    results = collection.query(
        query_embeddings=query_embedding,
        n_results=top_k_bi
    )

    if not results or not results['documents'] or not results['documents'][0]:
        print("⚠️ No records matched this query in the vector database.")
        return []

    documents = results['documents'][0]
    metadatas = results['metadatas'][0]
    ids = results['ids'][0]
    distances = results['distances'][0] if 'distances' in results and results['distances'] else [0.0]*len(documents)

    # 3. Prepare English pairs for Cross-Encoder scoring
    pairs = [[translated_query, doc] for doc in documents]
    cross_scores = cross_encoder.predict(pairs)

    candidates = []
    for idx in range(len(documents)):
        candidates.append({
            "id": ids[idx],
            "english_text": documents[idx],
            "hebrew_text": metadatas[idx].get("original_hebrew_text", "") if "original_hebrew_text" in metadatas[idx] else "",
            "source": metadatas[idx].get("source", "Unknown"),
            "bi_encoder_distance": distances[idx],
            "cross_encoder_score": float(cross_scores[idx]),
            "metadata": metadatas[idx]
        })

    # Sort candidates dynamically by relevance
    reranked_candidates = sorted(candidates, key=lambda x: x["cross_encoder_score"], reverse=True)
    return reranked_candidates[:top_k_cross]

