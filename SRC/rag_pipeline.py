def generate_grounded_answer(query_english: str) -> Tuple[str, List[Dict[str, Any]]]:
    # 1. Retrieve the top 3 high-relevance re-ranked context chunks using our bilingual pipeline
    # Passing the query directly; retrieve_and_rerank handles the vector search and cross-encoder re-ranking.
    retrieved_chunks = retrieve_and_rerank(query_english, top_k_bi=20, top_k_cross=3)

    # 2. Pre-LLM Retrieval Guardrail Check
    if not retrieved_chunks:
        return "I don't know based on the provided context.", []

    # Assemble context block with explicit source citations
    context_elements = []
    for idx, chunk in enumerate(retrieved_chunks, 1):
        citation = f"[Source {idx}: {chunk['source']} (ID: {chunk['id']})]"
        # ONLY include English text to save tokens
        text_content = f"{chunk['english_text']}"
        context_elements.append(f"{citation}\n{text_content}")

    combined_context = "\n\n---\n\n".join(context_elements)

    # Get secure API Key
    api_key = get_secret("OPENAI_API_KEY")
    if not api_key:
        return "❌ Error: OPENAI_API_KEY not found in Colab secrets. Please configure it under the lock icon.", []

    client = OpenAI(api_key=api_key)

    system_instruction = (
        "You are a strict grounded AI assistant. You answer municipal, infrastructure, and transportation safety questions "
        "exclusively using the provided context passages (which have been translated to English).\n\n"
        "CONTRACT RULES:\n"
        "1. Rely ONLY on the provided context. Do NOT use external or pre-trained knowledge to assume or extrapolate facts.\n"
        "2. You must reply in clear English.\n"
        "3. For any statement or fact you write, you MUST cite the source from the context using the exact inline tag, "
        "for example: [Source X: filename.pdf (ID: chunk_id)].\n"
        "4. Crucially: If the answer is not explicitly present in the provided context, you must reply exactly: "
        "\"I don't know based on the provided context.\""
    )

    user_prompt = f"Context:\n{combined_context}\n\nQuestion:\n{query_english}"

    max_retries = 2
    delay = 2.0
    for attempt in range(max_retries):
        try:
            response = client.chat.completions.create(
                model="gpt-4o-mini",
                messages=[
                    {"role": "system", "content": system_instruction},
                    {"role": "user", "content": user_prompt}
                ],
                temperature=0.1,
                max_tokens=512
            )
            answer_text = response.choices[0].message.content.strip()
            if answer_text:
                return answer_text, retrieved_chunks
        except Exception as e:
            print(f"⚠️ gpt-4o-mini encountered error (Attempt {attempt+1}/{max_retries}): {e}.")
            if attempt < max_retries - 1:
                print(f"Retrying in {delay}s...")
                time.sleep(delay)
                delay *= 2.0

    return "❌ API Call Failed after trying gpt-4o-mini.", []

