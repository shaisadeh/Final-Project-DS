    english_chunks_export = []
    for i in range(len(db_data['ids'])):
        chunk_entry = {
            "id": db_data['ids'][i],
            "english_text": db_data['documents'][i],
            "metadata": db_data['metadatas'][i].copy() # Copy to safely modify
        }

        # Strictly remove the original Hebrew text from the metadata to save tokens/space
        if 'original_hebrew_text' in chunk_entry['metadata']:
            del chunk_entry['metadata']['original_hebrew_text']

        english_chunks_export.append(chunk_entry)

    english_export_path = "english_vector_corpus_backup.json"

    # Save the strictly English chunks to JSON
    with open(english_export_path, "w", encoding="utf-8") as f:
        json.dump(english_chunks_export, f, indent=4, ensure_ascii=False)

    print(f"✅ Successfully exported {len(english_chunks_export)} strictly English chunks to {english_export_path}")

    # Trigger automatic download
